import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.preprocessing import MinMaxScaler
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import GRU
from tensorflow.keras.layers import LSTM
from tensorflow.keras.layers import Dense
from tensorflow.keras.layers import Dropout
from torch.utils.data import Dataset, DataLoader
import os

file_path = os.path.join("data", "AAPL.csv")
df = pd.read_csv(file_path)

df.sample(10)

df.isnull().values.any()  #no nan values

import matplotlib.pyplot as plt
plt.plot(df['Close'])

from sklearn.preprocessing import MinMaxScaler

df1 = df[['Open','High','Low','Close','Volume']]
df1.head()

data = df1.values

scaler = MinMaxScaler()

data_scaled = scaler.fit_transform(data)

data_scaled[:5]

data_scaled.shape

def create_dataset(dataset , timestep):
  X_data=[]
  y_data=[]

  for i in range(len(dataset)-timestep-1): # i=0 to 10348
    X_data.append(dataset[i:i+timestep])  #(0-60),(1-61),....
    y_data.append(dataset[i + timestep, 3])   # dataset[i + time_step, target_column]

  return np.array(X_data), np.array(y_data)

time_step = 60
X, y = create_dataset(data_scaled, time_step)

y[:5]

split = int(len(X) * 0.8)  #Take 80% of the data for training.

#First 800 samples → training
#Last 200 samples → testing

X_train = X[:split]
X_test = X[split:]

y_train = y[:split]
y_test = y[split:]

from tensorflow.keras.layers import Input

model=Sequential()
model.add(Input(shape=(60,5))) # Explicitly define input shape using Input layer
model.add(LSTM(64 , return_sequences=True))
model.add(Dropout(0.2))
model.add(LSTM(64, return_sequences=False))
model.add(Dropout(0.2))
model.add(Dense(32 ,activation='relu'))
model.add(Dense(1))

model.compile(optimizer='adam',
              loss='mse')

model.fit(
    X_train,
    y_train,
    epochs=20,
    batch_size=32,
    validation_data=(X_test, y_test))

predicted = model.predict(X_test)

model.evaluate(X_test,y_test)

y_test[:5]

dummy = np.zeros((len(predicted), 5))

dummy[:, 3] = predicted.flatten()   # Close column

predicted_price = scaler.inverse_transform(dummy)[:, 3]

dummy = np.zeros((len(y_test), 5))

dummy[:, 3] = y_test

actual_price = scaler.inverse_transform(dummy)[:, 3]

for i in range(5):
    print(f"Actual: {actual_price[i]:.2f} | Predicted: {predicted_price[i]:.2f}")

import matplotlib.pyplot as plt

plt.figure(figsize=(12,6))

plt.plot(actual_price, label='Actual Close')
plt.plot(predicted_price, label='Predicted Close')

plt.xlabel("Time")
plt.ylabel("Stock Price")
plt.legend()

plt.show()

from sklearn.metrics import (
    mean_squared_error,
    mean_absolute_error,
    mean_absolute_percentage_error,
    r2_score
)
import numpy as np

rmse = np.sqrt(mean_squared_error(actual_price, predicted_price))
mae = mean_absolute_error(actual_price, predicted_price)
mape = mean_absolute_percentage_error(actual_price, predicted_price) * 100
r2 = r2_score(actual_price, predicted_price)

print(f"RMSE : {rmse:.2f}")
print(f"MAE  : {mae:.2f}")
print(f"MAPE : {mape:.2f}%")
print(f"R²   : {r2:.4f}")

# Last 60 days
last_60 = data_scaled[-60:]

# Reshape for LSTM
X_new = last_60.reshape(1, 60, 5)

# Predict
pred = model.predict(X_new)

# Convert back to original price
dummy = np.zeros((1, 5))
dummy[:, 3] = pred.flatten()

predicted_close = scaler.inverse_transform(dummy)[:, 3]

print("Predicted Next Day Close Price:", predicted_close[0])

